import { DEFAULT_CROP } from '../core/geometry';
import type { Photo } from '../core/images';
import {
  aspectRatio, clipStrayOverflow, groupOf, newId, type El, type Page, type PhotoEl, type Story, type TextEl,
} from './model';
import { ARRANGEMENTS, arrangementLabel, GROUP_ORDER, pickableFinishes, type Arrangement, type Group } from './arrangements';
import { resolveFinish } from './finishes';
import { getTemplate, orientationOf, type Orient, type Template } from './templates';
import type { FinishId } from './templateAliases';

/** One arrangement the layout picker can offer for a page (or a spread group), shown in the finish the page has now where that is allowed. */
export type LayoutOption = {
  /** Unique within one `layoutOptions` result (the arrangement id, or 'full-each'). */
  id: string;
  name: string;
  arrangement: string | typeof FULL_EACH;
  group: Group;
  /** Finish this option applies: the page's current finish when the arrangement allows it, else its default. Null for built-in looks. */
  finish: FinishId | null;
  /** Finishes the user can pick for this arrangement (empty when it has a single look). */
  finishes: FinishId[];
  /** Photos the layout shows. */
  slots: number;
  /** Pages it produces. */
  pages: number;
  /** True for the arrangement the page uses now. */
  current: boolean;
  /** True for "more or fewer photos" options (their slot count differs from the page's photo count). */
  slotsDiffer: boolean;
};

export const FULL_EACH = 'full-each' as const;
export const MAX_SLOTS = 9;
const COVERS = new Set(['cover', 'cover-sans', 'cover-border', 'cover-border-below', 'cover-mat']);
/** Templates whose text (title, subtitle, caption) is generated by the template itself. */
const TEXT_TEMPLATES = new Set(['cover', 'cover-sans', 'cover-border', 'cover-border-below', 'cover-mat', 'title-card', 'magazine', 'polaroid-on-photo']);

/* ---------- reading a page ---------- */

type Context = {
  start: number;
  end: number;
  pages: Page[];
  /** Photo element per slot, in page order then element order. */
  slots: PhotoEl[];
  title: string | undefined;
  subtitle: string | undefined;
};

const norm = (s: string) => s.replace(/\s+/g, ' ').trim().toLowerCase();

/** Text the current template generated (cover title etc.), as opposed to text the user added. */
function ownedTexts(pages: Page[]): TextEl[] {
  if (!TEXT_TEMPLATES.has(getTemplate(pages[0]?.templateId)?.id ?? '')) return [];
  return pages.flatMap((p) => p.elements.filter((e): e is TextEl => e.kind === 'text' && !!e.text.trim()));
}

function contextOf(story: Story, pageIndex: number): Context | null {
  if (!story.pages[pageIndex]) return null;
  const { start, end } = groupOf(story, pageIndex);
  const pages = story.pages.slice(start, end);
  const slots = pages.flatMap((p) => p.elements.filter((e): e is PhotoEl => e.kind === 'photo'));
  const owned = ownedTexts(pages);
  return { start, end, pages, slots, title: owned[0]?.text || story.title.trim() || undefined, subtitle: owned[1]?.text || undefined };
}

const photoOf = (story: Story, id: string | null): Photo | undefined => (id ? story.photos.find((p) => p.id === id) : undefined);

/** Background the template itself sets (film strips are black), or undefined when it just uses the page's. */
function templateBackground(t: Template, aspect: Story['aspect']): string | undefined {
  const bg = t.layout(aspect, []).backgrounds[0];
  return bg && bg.toLowerCase() !== '#ffffff' ? bg : undefined;
}

/* ---------- options ---------- */

const mostCommon = (o: Orient[]): Orient => {
  const n = { p: 0, l: 0, s: 0 };
  for (const x of o) n[x]++;
  return (['l', 'p', 's'] as Orient[]).reduce((a, b) => (n[b] > n[a] ? b : a));
};

/** The arrangement and finish the page's group uses now (null when it matches no layout). */
export function currentOf(story: Story, pageIndex: number): { arrangement: Arrangement; finish: FinishId | null } | null {
  const { start } = groupOf(story, pageIndex);
  const lead = story.pages[start];
  const t = lead && getTemplate(lead.templateId, lead.finish);
  return t ? { arrangement: t.arrangement, finish: t.finish } : null;
}

/**
 * Arrangements to offer for the page (its whole spread group counts as one unit), each in the page's current finish where allowed.
 * Order: by group (cover, single, multiple, across pages, special), best fit first inside a group (a poor fit is left out unless it is the current one),
 * with "Full screen, one per page" leading the Single group for several photos. Arrangements for other photo counts (`slotsDiffer`) follow, nearest first.
 */
export function layoutOptions(story: Story, pageIndex: number): LayoutOption[] {
  const ctx = contextOf(story, pageIndex);
  if (!ctx || ctx.slots.length === 0) return [];
  const n = ctx.slots.length;
  const cur = currentOf(story, pageIndex);
  const currentId = cur?.arrangement.id;
  const orient: Orient[] = ctx.slots.map((e) => {
    const p = photoOf(story, e.photoId);
    return p ? orientationOf(p) : 's';
  });
  const pad = mostCommon(orient);
  const hasTitle = !!ctx.title;
  const rank = new Map(ARRANGEMENTS.map((a, i) => [a.id, i]));
  const gi = (a: Arrangement) => GROUP_ORDER.indexOf(a.group);
  const opt = (a: Arrangement, differ: boolean): LayoutOption => {
    const isCurrent = a.id === currentId;
    const finish = isCurrent ? cur!.finish : resolveFinish(a, cur?.finish);
    return { id: a.id, name: a.name, arrangement: a.id, group: a.group, finish, finishes: pickableFinishes(a), slots: a.slots, pages: a.pages, current: isCurrent, slotsDiffer: differ };
  };
  const usable = (a: Arrangement) => a.slots >= 1 && a.slots <= MAX_SLOTS && (hasTitle || !COVERS.has(a.id));

  const same: { a: Arrangement; s: number }[] = [];
  const differ: { a: Arrangement; s: number; d: number }[] = [];
  for (const a of ARRANGEMENTS) {
    if (!usable(a)) continue;
    const o = n >= a.slots ? orient.slice(0, a.slots) : orient.concat(Array.from({ length: a.slots - n }, () => pad));
    const s = a.fits(o, story.aspect);
    if (s <= 0 && a.id !== currentId) continue;
    if (a.slots === n) same.push({ a, s });
    else differ.push({ a, s, d: Math.abs(a.slots - n) });
  }
  same.sort((x, y) => gi(x.a) - gi(y.a) || y.s - x.s || rank.get(x.a.id)! - rank.get(y.a.id)!);
  differ.sort((x, y) => x.d - y.d || y.s - x.s || rank.get(x.a.id)! - rank.get(y.a.id)!);

  const out: LayoutOption[] = same.map((x) => opt(x.a, false));
  if (n > 1) {
    const full: LayoutOption = { id: FULL_EACH, name: 'Full screen, one per page', arrangement: FULL_EACH, group: 'single', finish: 'bleed', finishes: [], slots: n, pages: n, current: false, slotsDiffer: false };
    const at = out.findIndex((o) => o.group === 'single' || GROUP_ORDER.indexOf(o.group) > GROUP_ORDER.indexOf('single'));
    out.splice(at < 0 ? out.length : at, 0, full);
  }
  out.push(...differ.map((x) => opt(x.a, true)));
  return out;
}

/* ---------- applying ---------- */

/** What to apply: an arrangement and optionally a finish (a `LayoutOption` fits). */
export type LayoutTarget = { arrangement: string; finish?: FinishId | null };

export type ApplyOpts = {
  seed: number;
  /** Photos (already in `story.photos`) to fill extra slots with, in order, before leaving placeholders. Ones already on the page are skipped. */
  extraPhotoIds?: string[];
  /** Gutter and outer margin (fractions of page width) handed to the arrangement; the arrangement's defaults when absent. */
  gap?: number;
  margin?: number;
};

const aspectOf = (e: PhotoEl, A: number) => (e.w * A) / Math.max(1e-9, e.h);

/** Reuse the crop of an earlier frame showing the same photo when the new frame has about the same shape. */
function keepCrop(el: El, prior: Map<string, PhotoEl[]>, A: number): El {
  if (el.kind !== 'photo' || !el.photoId) return el;
  const list = prior.get(el.photoId);
  if (!list?.length) return el;
  const na = aspectOf(el, A);
  const at = list.findIndex((o) => Math.abs(Math.log(aspectOf(o, A) / na)) < 0.15);
  if (at < 0) return { ...el, crop: { ...DEFAULT_CROP } };
  const [match] = list.splice(at, 1);
  return { ...el, crop: { ...match.crop } };
}

/**
 * Replace the page (its whole spread group) with the option's layout, using the page's photos in their current order.
 * Page ids, durations and the background are kept; text the user added moves to the first page. Returns the new story and the page to show.
 */
export function applyLayout(story: Story, pageIndex: number, option: LayoutTarget, opts: ApplyOpts): { story: Story; pageIndex: number } {
  const ctx = contextOf(story, pageIndex);
  const full = option.arrangement === FULL_EACH;
  const t = full ? getTemplate('single', 'bleed') : getTemplate(option.arrangement, option.finish);
  if (!ctx || !t) return { story, pageIndex };
  const A = aspectRatio(story.aspect);

  // Photos in order; the layout's slot count decides how many are used.
  const ids: (string | null)[] = ctx.slots.map((e) => (e.photoId && photoOf(story, e.photoId) ? e.photoId : null));
  const want = full ? ids.length : t.slots;
  const chosen: (string | null)[] = ids.slice(0, want);
  if (chosen.length < want) {
    const have = new Set(ids);
    for (const id of opts.extraPhotoIds ?? []) {
      if (chosen.length >= want) break;
      if (have.has(id) || !photoOf(story, id)) continue;
      chosen.push(id);
      have.add(id);
    }
    while (chosen.length < want) chosen.push(null);
  }

  // Template-generated text is regenerated by text templates; everything else rides along on the first page.
  const owned = new Set(ownedTexts(ctx.pages).map((e) => e.id));
  const textTemplate = TEXT_TEMPLATES.has(t.id) && !full;
  const generated = new Set<string>();
  if (textTemplate) {
    if (ctx.title) generated.add(norm(ctx.title));
    if (ctx.subtitle) generated.add(norm(ctx.subtitle));
  }
  const kept = ctx.pages.flatMap((p) => p.elements.filter((e): e is TextEl => e.kind === 'text' && !(textTemplate && (owned.has(e.id) || generated.has(norm(e.text))))));

  const layouts: { photos: (string | null)[] }[] = full ? chosen.map((id) => ({ photos: [id] })) : [{ photos: chosen }];
  const prior = new Map<string, PhotoEl[]>();
  for (const e of ctx.slots) if (e.photoId) prior.set(e.photoId, [...(prior.get(e.photoId) ?? []), e]);
  const lead = ctx.pages[0];
  const leadTemplate = getTemplate(lead.templateId, lead.finish);
  const oldBg = leadTemplate ? templateBackground(leadTemplate, story.aspect) : undefined;
  const ownBg = templateBackground(t, story.aspect);

  const fresh: Page[] = [];
  for (const l of layouts) {
    const res = t.layout(story.aspect, l.photos.map((id) => photoOf(story, id)) as Photo[], { title: ctx.title, subtitle: ctx.subtitle, caption: ctx.title, seed: opts.seed, ...(opts.gap !== undefined ? { gap: opts.gap } : {}), ...(opts.margin !== undefined ? { margin: opts.margin } : {}) });
    res.pages.forEach((els, i) => {
      const k = fresh.length;
      const old = ctx.pages[k] ?? lead;
      fresh.push({
        id: ctx.pages[k]?.id ?? newId(),
        templateId: t.id,
        ...(t.finish ? { finish: t.finish } : {}),
        background: ownBg ?? (oldBg && old.background === oldBg ? story.background : old.background),
        elements: els.map((e) => keepCrop(e, prior, A)),
        duration: ctx.pages[k]?.duration ?? lead.duration,
        ...(t.pageCount > 1 ? { spread: { index: i, count: t.pageCount } } : {}),
      });
    });
  }
  if (kept.length) {
    const first = fresh[0];
    const top = Math.max(-1, ...first.elements.map((e) => e.z));
    first.elements = [...first.elements, ...kept.map((e, i): El => ({ ...e, z: top + 1 + i }))];
  }
  const pages = [...story.pages.slice(0, ctx.start), ...fresh, ...story.pages.slice(ctx.end)];
  const offset = Math.max(0, Math.min(pageIndex - ctx.start, fresh.length - 1));
  return { story: clipStrayOverflow({ ...story, pages }), pageIndex: ctx.start + offset };
}

/**
 * The arrangement to switch to when stepping through the page's same-photo-count arrangements, after the current one, wrapping.
 * It keeps the page's finish when the arrangement allows it (else uses that arrangement's default).
 * "One per page" is not part of the cycle because it changes the page count. Null when there is nothing else to switch to.
 */
export function nextLayout(story: Story, pageIndex: number, direction: 1 | -1): LayoutOption | null {
  const cycle = layoutOptions(story, pageIndex).filter((o) => !o.slotsDiffer && o.arrangement !== FULL_EACH);
  if (cycle.length === 0) return null;
  const at = cycle.findIndex((o) => o.current);
  if (at < 0) return direction === 1 ? cycle[0] : cycle[cycle.length - 1];
  if (cycle.length === 1) return null;
  return cycle[(at + direction + cycle.length) % cycle.length];
}

/** The next / previous finish the page's arrangement allows, wrapping. Null when it has only one look. */
export function nextFinish(story: Story, pageIndex: number, direction: 1 | -1): { arrangement: string; finish: FinishId } | null {
  const cur = currentOf(story, pageIndex);
  if (!cur) return null;
  const list = pickableFinishes(cur.arrangement);
  if (list.length < 2) return null;
  const at = Math.max(0, list.indexOf(cur.finish as FinishId));
  return { arrangement: cur.arrangement.id, finish: list[(at + direction + list.length) % list.length] };
}

/** Finish the page's group uses now (null for built-in looks and unknown layouts). */
export function currentFinish(story: Story, pageIndex: number): FinishId | null {
  return currentOf(story, pageIndex)?.finish ?? null;
}

/** Name of the page's current layout for display, e.g. "Stack 3 · Black borders" ("Custom" when the page matches no template). */
export function currentLayoutName(story: Story, pageIndex: number): string {
  const cur = currentOf(story, pageIndex);
  return cur ? arrangementLabel(cur.arrangement, cur.finish) : 'Custom';
}

/** A stable seed for a page's layouts, so a thumbnail looks exactly like what applying it gives (and cycling is repeatable). */
export function pageSeed(story: Story, pageIndex: number): number {
  const id = story.pages[groupOf(story, pageIndex).start]?.id ?? '';
  let h = 2166136261;
  for (let i = 0; i < id.length; i++) h = Math.imul(h ^ id.charCodeAt(i), 16777619);
  return (h >>> 0) & 0x7fffffff;
}

/** Text elements on the page's group that the user added (not generated by a text template such as a cover). */
export function userTexts(story: Story, pageIndex: number): TextEl[] {
  const ctx = contextOf(story, pageIndex);
  if (!ctx) return [];
  const owned = new Set(ownedTexts(ctx.pages).map((e) => e.id));
  return ctx.pages.flatMap((p) => p.elements.filter((e): e is TextEl => e.kind === 'text' && !owned.has(e.id)));
}

/** Everything about the page's group that affects what its layouts look like, as a string (for caching previews). */
export function layoutSignature(story: Story, pageIndex: number): string {
  const { start, end } = groupOf(story, pageIndex);
  return JSON.stringify([story.aspect, story.title, story.background, story.pages.slice(start, end), story.photos.map((p) => [p.id, p.width, p.height])]);
}
