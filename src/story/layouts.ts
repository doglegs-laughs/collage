import { DEFAULT_CROP } from '../core/geometry';
import type { Photo } from '../core/images';
import {
  aspectRatio, clipStrayOverflow, groupOf, newId, type El, type Page, type PhotoEl, type Story, type TextEl,
} from './model';
import { getTemplate, orientationOf, TEMPLATES, type Orient, type Template } from './templates';

/** One thing the layout picker can offer for a page (or a spread group). */
export type LayoutOption = {
  /** Unique within one `layoutOptions` result (the template id, or 'full-each'). */
  id: string;
  name: string;
  templateId: string | 'full-each';
  /** Photos the layout shows. */
  slots: number;
  /** Pages it produces. */
  pages: number;
  /** True for the layout the page uses now. */
  current: boolean;
  /** True for "more or fewer photos" options (their slot count differs from the page's photo count). */
  slotsDiffer: boolean;
};

export const FULL_EACH = 'full-each';
export const MAX_SLOTS = 9;
const BLEED = 'single-bleed';
const COVERS = new Set(['cover', 'cover-sans']);
/** Templates whose text (title, subtitle, caption) is generated by the template itself. */
const TEXT_TEMPLATES = new Set(['cover', 'cover-sans', 'title-card', 'magazine', 'polaroid-on-photo']);

/* ---------- reading a page ---------- */

type Context = {
  start: number;
  end: number;
  pages: Page[];
  /** Photo element per slot, in page order then element order. */
  slots: PhotoEl[];
  title: string | undefined;
  subtitle: string | undefined;
};

const norm = (s: string) => s.replace(/\s+/g, ' ').trim().toLowerCase();

/** Text the current template generated (cover title etc.), as opposed to text the user added. */
function ownedTexts(pages: Page[]): TextEl[] {
  if (!TEXT_TEMPLATES.has(pages[0]?.templateId ?? '')) return [];
  return pages.flatMap((p) => p.elements.filter((e): e is TextEl => e.kind === 'text' && !!e.text.trim()));
}

function contextOf(story: Story, pageIndex: number): Context | null {
  if (!story.pages[pageIndex]) return null;
  const { start, end } = groupOf(story, pageIndex);
  const pages = story.pages.slice(start, end);
  const slots = pages.flatMap((p) => p.elements.filter((e): e is PhotoEl => e.kind === 'photo'));
  const owned = ownedTexts(pages);
  return { start, end, pages, slots, title: owned[0]?.text || story.title.trim() || undefined, subtitle: owned[1]?.text || undefined };
}

const photoOf = (story: Story, id: string | null): Photo | undefined => (id ? story.photos.find((p) => p.id === id) : undefined);

/** Background the template itself sets (film strips are black), or undefined when it just uses the page's. */
function templateBackground(t: Template, aspect: Story['aspect']): string | undefined {
  const bg = t.layout(aspect, []).backgrounds[0];
  return bg && bg.toLowerCase() !== '#ffffff' ? bg : undefined;
}

/* ---------- options ---------- */

const mostCommon = (o: Orient[]): Orient => {
  const n = { p: 0, l: 0, s: 0 };
  for (const x of o) n[x]++;
  return (['l', 'p', 's'] as Orient[]).reduce((a, b) => (n[b] > n[a] ? b : a));
};

/**
 * Layouts to offer for the page (its whole spread group counts as one unit).
 * Order: Full screen photo (one photo) or "Full screen, one per page" (several), then templates that take exactly this many photos
 * (best fit first, then catalog order; a poor fit is left out unless it is the current layout), then the `slotsDiffer` group for other photo counts, nearest first.
 */
export function layoutOptions(story: Story, pageIndex: number): LayoutOption[] {
  const ctx = contextOf(story, pageIndex);
  if (!ctx || ctx.slots.length === 0) return [];
  const n = ctx.slots.length;
  const currentId = ctx.pages[0].templateId;
  const orient: Orient[] = ctx.slots.map((e) => {
    const p = photoOf(story, e.photoId);
    return p ? orientationOf(p) : 's';
  });
  const pad = mostCommon(orient);
  const hasTitle = !!ctx.title;
  const rank = new Map(TEMPLATES.map((t, i) => [t.id, i]));
  const opt = (t: Template, differ: boolean): LayoutOption => ({
    id: t.id, name: t.id === BLEED ? 'Full screen photo' : t.name, templateId: t.id, slots: t.slots, pages: t.pageCount, current: t.id === currentId, slotsDiffer: differ,
  });
  const usable = (t: Template) => t.slots >= 1 && t.slots <= MAX_SLOTS && (hasTitle || !COVERS.has(t.id));

  const same: { t: Template; s: number }[] = [];
  const differ: { t: Template; s: number; d: number }[] = [];
  for (const t of TEMPLATES) {
    if (!usable(t)) continue;
    const o = n >= t.slots ? orient.slice(0, t.slots) : orient.concat(Array.from({ length: t.slots - n }, () => pad));
    const s = t.fits(o, story.aspect);
    if (s <= 0 && t.id !== currentId) continue;
    if (t.slots === n) same.push({ t, s });
    else differ.push({ t, s, d: Math.abs(t.slots - n) });
  }
  same.sort((a, b) => (a.t.id === BLEED ? -1 : b.t.id === BLEED ? 1 : 0) || b.s - a.s || rank.get(a.t.id)! - rank.get(b.t.id)!);
  differ.sort((a, b) => a.d - b.d || b.s - a.s || rank.get(a.t.id)! - rank.get(b.t.id)!);

  const out: LayoutOption[] = [];
  if (n === 1) {
    if (!same.some((x) => x.t.id === BLEED)) out.push(opt(getTemplate(BLEED)!, false));
  } else {
    out.push({ id: FULL_EACH, name: 'Full screen, one per page', templateId: FULL_EACH, slots: n, pages: n, current: false, slotsDiffer: false });
  }
  out.push(...same.map((x) => opt(x.t, false)), ...differ.map((x) => opt(x.t, true)));
  return out;
}

/* ---------- applying ---------- */

export type ApplyOpts = {
  seed: number;
  /** Photos (already in `story.photos`) to fill extra slots with, in order, before leaving placeholders. Ones already on the page are skipped. */
  extraPhotoIds?: string[];
};

const aspectOf = (e: PhotoEl, A: number) => (e.w * A) / Math.max(1e-9, e.h);

/** Reuse the crop of an earlier frame showing the same photo when the new frame has about the same shape. */
function keepCrop(el: El, prior: Map<string, PhotoEl[]>, A: number): El {
  if (el.kind !== 'photo' || !el.photoId) return el;
  const list = prior.get(el.photoId);
  if (!list?.length) return el;
  const na = aspectOf(el, A);
  const at = list.findIndex((o) => Math.abs(Math.log(aspectOf(o, A) / na)) < 0.15);
  if (at < 0) return { ...el, crop: { ...DEFAULT_CROP } };
  const [match] = list.splice(at, 1);
  return { ...el, crop: { ...match.crop } };
}

/**
 * Replace the page (its whole spread group) with the option's layout, using the page's photos in their current order.
 * Page ids, durations and the background are kept; text the user added moves to the first page. Returns the new story and the page to show.
 */
export function applyLayout(story: Story, pageIndex: number, option: LayoutOption, opts: ApplyOpts): { story: Story; pageIndex: number } {
  const ctx = contextOf(story, pageIndex);
  const full = option.templateId === FULL_EACH;
  const t = getTemplate(full ? BLEED : option.templateId);
  if (!ctx || !t) return { story, pageIndex };
  const A = aspectRatio(story.aspect);

  // Photos in order; the layout's slot count decides how many are used.
  const ids: (string | null)[] = ctx.slots.map((e) => (e.photoId && photoOf(story, e.photoId) ? e.photoId : null));
  const want = full ? ids.length : t.slots;
  const chosen: (string | null)[] = ids.slice(0, want);
  if (chosen.length < want) {
    const have = new Set(ids);
    for (const id of opts.extraPhotoIds ?? []) {
      if (chosen.length >= want) break;
      if (have.has(id) || !photoOf(story, id)) continue;
      chosen.push(id);
      have.add(id);
    }
    while (chosen.length < want) chosen.push(null);
  }

  // Template-generated text is regenerated by text templates; everything else rides along on the first page.
  const owned = new Set(ownedTexts(ctx.pages).map((e) => e.id));
  const textTemplate = TEXT_TEMPLATES.has(t.id) && !full;
  const generated = new Set<string>();
  if (textTemplate) {
    if (ctx.title) generated.add(norm(ctx.title));
    if (ctx.subtitle) generated.add(norm(ctx.subtitle));
  }
  const kept = ctx.pages.flatMap((p) => p.elements.filter((e): e is TextEl => e.kind === 'text' && !(textTemplate && (owned.has(e.id) || generated.has(norm(e.text))))));

  const layouts: { photos: (string | null)[] }[] = full ? chosen.map((id) => ({ photos: [id] })) : [{ photos: chosen }];
  const prior = new Map<string, PhotoEl[]>();
  for (const e of ctx.slots) if (e.photoId) prior.set(e.photoId, [...(prior.get(e.photoId) ?? []), e]);
  const lead = ctx.pages[0];
  const leadTemplate = getTemplate(lead.templateId);
  const oldBg = leadTemplate ? templateBackground(leadTemplate, story.aspect) : undefined;
  const ownBg = templateBackground(t, story.aspect);

  const fresh: Page[] = [];
  for (const l of layouts) {
    const res = t.layout(story.aspect, l.photos.map((id) => photoOf(story, id)) as Photo[], { title: ctx.title, subtitle: ctx.subtitle, caption: ctx.title, seed: opts.seed });
    res.pages.forEach((els, i) => {
      const k = fresh.length;
      const old = ctx.pages[k] ?? lead;
      fresh.push({
        id: ctx.pages[k]?.id ?? newId(),
        templateId: t.id,
        background: ownBg ?? (oldBg && old.background === oldBg ? story.background : old.background),
        elements: els.map((e) => keepCrop(e, prior, A)),
        duration: ctx.pages[k]?.duration ?? lead.duration,
        ...(t.pageCount > 1 ? { spread: { index: i, count: t.pageCount } } : {}),
      });
    });
  }
  if (kept.length) {
    const first = fresh[0];
    const top = Math.max(-1, ...first.elements.map((e) => e.z));
    first.elements = [...first.elements, ...kept.map((e, i): El => ({ ...e, z: top + 1 + i }))];
  }
  const pages = [...story.pages.slice(0, ctx.start), ...fresh, ...story.pages.slice(ctx.end)];
  const offset = Math.max(0, Math.min(pageIndex - ctx.start, fresh.length - 1));
  return { story: clipStrayOverflow({ ...story, pages }), pageIndex: ctx.start + offset };
}

/**
 * The option to switch to when stepping through the page's same-photo-count layouts (Full screen included), after the current one, wrapping.
 * "One per page" is not part of the cycle because it changes the page count. Null when there is nothing else to switch to.
 */
export function nextLayout(story: Story, pageIndex: number, direction: 1 | -1): LayoutOption | null {
  const cycle = layoutOptions(story, pageIndex).filter((o) => !o.slotsDiffer && o.templateId !== FULL_EACH);
  if (cycle.length === 0) return null;
  const at = cycle.findIndex((o) => o.current);
  if (at < 0) return direction === 1 ? cycle[0] : cycle[cycle.length - 1];
  if (cycle.length === 1) return null;
  return cycle[(at + direction + cycle.length) % cycle.length];
}

/** Name of the page's current layout for display ("Custom" when the page matches no template). */
export function currentLayoutName(story: Story, pageIndex: number): string {
  const id = story.pages[pageIndex]?.templateId;
  if (id === BLEED) return 'Full screen photo';
  return getTemplate(id)?.name ?? 'Custom';
}

/** A stable seed for a page's layouts, so a thumbnail looks exactly like what applying it gives (and cycling is repeatable). */
export function pageSeed(story: Story, pageIndex: number): number {
  const id = story.pages[groupOf(story, pageIndex).start]?.id ?? '';
  let h = 2166136261;
  for (let i = 0; i < id.length; i++) h = Math.imul(h ^ id.charCodeAt(i), 16777619);
  return (h >>> 0) & 0x7fffffff;
}

/** Everything about the page's group that affects what its layouts look like, as a string (for caching previews). */
export function layoutSignature(story: Story, pageIndex: number): string {
  const { start, end } = groupOf(story, pageIndex);
  return JSON.stringify([story.aspect, story.title, story.background, story.pages.slice(start, end), story.photos.map((p) => [p.id, p.width, p.height])]);
}
